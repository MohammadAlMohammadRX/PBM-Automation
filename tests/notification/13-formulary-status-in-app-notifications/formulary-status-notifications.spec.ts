import { test, expect } from '../../../fixtures';
import type { InboxNotification } from '../../../utils/notification/notificationApi';
import { readFormulary, type ProvisionedFormulary } from '../../../utils/FormularyProvisioning';
import type { StatusKind } from '../../../constants/notification/writerEIds';
import {
  activeFormulary,
  anyNotificationsAbout,
  awaitReminder,
  bellRowFor,
  blockUnless,
  deactivateFormulary,
  discardSuiteFormularies,
  entityVariable,
  expiredNotification,
  fireAndAwait,
  formularyExpiredByJob,
  formularyGoingLive,
  formularyRef,
  hasPlaceholder,
  inMs,
  inWindowExpiry,
  notificationsAbout,
  outOfWindowExpiry,
  reminderDays,
  riyadhDayDiff,
  sameDay,
  specNames,
  statusDefinition,
  statusDefinitions,
  statusOf,
  valuesOf,
  waitForNotificationAbout,
  waitForStatus,
  type FormularyExpiryRun,
  type Inactivation,
  type ProbeDefinition,
} from '../../../utils/notification/writerEHelpers';
import {
  CASES,
  DEACTIVATION_DETAILS,
  FORMULARY_NOT_ACTIVATED,
  NO_REMINDER_RUN,
  REMINDER_FIRINGS,
  SHORT_EXPIRY_IN_MS,
  SPEC_VARIABLES,
  STORY,
  WATCH_MS,
} from '../../../data/notification/formularyStatusInAppNotifications.data';

/**
 * US 20996 - formulary status in-app notifications (no Active notification;
 * Inactive, Expired, Expiring Soon), driven by the suite's own formularies and
 * the formulary job (jobClock, restored after each firing). Each case saves its
 * own ACTIVE suite definitions (audience careconnect) before the transitions.
 * See data/notification/formularyStatusInAppNotifications.data.ts.
 */
test.describe(STORY, () => {
  test.describe.configure({ timeout: 30 * 60_000 });

  // The case's own formularies (built by suiteFormulary, which retries a transport error once) are discarded here.
  test.afterEach(async ({ page }) => {
    await discardSuiteFormularies(page);
  });

  test(`TC-${CASES.noActiveNotification.azureId}: should send no activation notification when the daily status update re-processes an Active formulary`, async ({ steps, page, jobClock, suiteDefinitions, ncDefinitions, notificationBell }) => {
    let def!: ProbeDefinition;
    let formulary!: ProvisionedFormulary;

    await steps.critical('Precondition: an Active suite formulary and an active "Active - Formulary" definition', async () => {
      formulary = await activeFormulary(page);
      def = await statusDefinition(page, suiteDefinitions, 'formulary', 'active');
      expect(await statusOf(page, 'formulary', formulary.id)).toBe('active');
    });

    await steps.step('Navigate to the Notification Center Management module - the module and the notification feed are shown', async () => {
      await ncDefinitions.open();
      expect(await ncDefinitions.rowIdByName(def.name)).toBe(def.id);
      await expect(notificationBell.bellButton()).toBeVisible();
    });

    await steps.step('Let the daily status update re-process the Active formulary - it remains Active', async () => {
      const run = await fireAndAwait(page, jobClock, 'formulary', [formulary.id], 'active', new Date());
      expect(run.statuses[formulary.id], `after the formulary job at ${run.firedAt.toISOString()}`).toBe('active');
    });

    await steps.step('Check the feed - no Active formulary notification is generated by the daily run', async () => {
      const seen = await anyNotificationsAbout(page, [def], formularyRef(formulary), WATCH_MS);
      expect(seen, `Active notifications about "${formulary.nameEn}"`).toEqual([]);
    });
  });

  test(`TC-${CASES.inactiveNotified.azureId}: should notify the audience when an approved formulary inactivation takes effect`, async ({ steps, page, suiteDefinitions, ncDefinitions, notificationBell }) => {
    let def!: ProbeDefinition;
    let formulary!: ProvisionedFormulary;
    let inactivation!: Inactivation;

    await steps.critical('Precondition: an Active suite formulary and an active "Inactive - Formulary" definition', async () => {
      formulary = await activeFormulary(page);
      def = await statusDefinition(page, suiteDefinitions, 'formulary', 'inactive');
      expect(await statusOf(page, 'formulary', formulary.id)).toBe('active');
    });

    await steps.step('Navigate to the Notification Center Management module - the module and the notification feed are shown', async () => {
      await ncDefinitions.open();
      expect(await ncDefinitions.rowIdByName(def.name)).toBe(def.id);
      await expect(notificationBell.bellButton()).toBeVisible();
    });

    await steps.step('Let the approved inactivation take effect - the formulary reads Inactive', async () => {
      inactivation = await deactivateFormulary(page, formulary, DEACTIVATION_DETAILS);
      expect((await waitForStatus(page, 'formulary', formulary.id, 'inactive', 60_000)).value).toBe('inactive');
    });

    await steps.step('Check the configured audience\'s feed - a new Inactive notification appears with the Inactive placeholder set', async () => {
      const n = await waitForNotificationAbout(page, def, formularyRef(formulary), 90_000);
      expect(n, `No "${def.name}" notification about "${formulary.nameEn}" arrived`).not.toBeNull();
      expect(specNames(def, 'formulary')).toEqual([...SPEC_VARIABLES.inactive].sort());
      const values = valuesOf(n);
      const record = await readFormulary(page, formulary.id);
      expect(values.InactivationReason, `InactivationReason in "${n?.englishMessage}"`).toBe(inactivation.reason);
      expect(
        sameDay(values.TransitionDate, inactivation.at),
        `TransitionDate "${values.TransitionDate}" should be the day the approved inactivation took effect (${inactivation.at.toISOString()}); the formulary's ExpiryDate is ${record.expiryDate}`,
      ).toBe(true);
      expect(hasPlaceholder(n?.englishMessage ?? '')).toBe(false);
      expect((await bellRowFor(notificationBell, def))?.type).toBe(def.name);
    });
  });

  test(`TC-${CASES.inactiveNamesFormulary.azureId}: should name the formulary in the Inactive formulary notification`, async ({ steps, page, suiteDefinitions, ncDefinitions, notificationBell }) => {
    let def!: ProbeDefinition;
    let formulary!: ProvisionedFormulary;
    let n: InboxNotification | null = null;

    await steps.critical('Precondition: an Inactive formulary notification has just been generated (own formulary, approved deactivation)', async () => {
      formulary = await activeFormulary(page);
      def = await statusDefinition(page, suiteDefinitions, 'formulary', 'inactive');
      await deactivateFormulary(page, formulary, DEACTIVATION_DETAILS);
      n = await waitForNotificationAbout(page, def, formularyRef(formulary), 90_000);
      expect(n, `"${def.name}" about "${formulary.nameEn}"`).not.toBeNull();
    });

    await steps.step('Navigate to the Notification Center Management module - the module and the notification feed are shown', async () => {
      await ncDefinitions.open();
      expect(await ncDefinitions.rowIdByName(def.name)).toBe(def.id);
      await expect(notificationBell.bellButton()).toBeVisible();
    });

    await steps.step('Open the Inactive formulary notification - its content is displayed', async () => {
      const row = await bellRowFor(notificationBell, def);
      expect(row, 'the notification is listed in the bell').not.toBeNull();
      expect(row?.text ?? '').toContain(def.marker);
    });

    await steps.step('Review the {{Entity}} value - it matches the formulary\'s name', async () => {
      expect(valuesOf(n)[entityVariable(def, 'formulary')], `the entity in "${n?.englishMessage}"`).toBe(formulary.nameEn);
    });
  });

  test(`TC-${CASES.expiredNotified.azureId}: should notify the audience with ExpiryDate and TransitionDate when the daily status update expires a formulary`, async ({ steps, page, jobClock, suiteDefinitions, ncDefinitions, notificationBell }) => {
    let def!: ProbeDefinition;
    let formulary!: ProvisionedFormulary;
    let expiryAt = new Date();
    let firedAt = new Date();

    await steps.critical('Precondition: an active "Expired - Formulary" definition and a suite formulary made Active by the formulary job, expiring minutes later', async () => {
      def = await statusDefinition(page, suiteDefinitions, 'formulary', 'expired');
      expiryAt = inMs(SHORT_EXPIRY_IN_MS);
      const live = await formularyGoingLive(page, expiryAt);
      formulary = live.formulary;
      const f1 = await fireAndAwait(page, jobClock, 'formulary', [formulary.id], 'active', live.effectiveAt);
      blockUnless(steps, f1.ok, FORMULARY_NOT_ACTIVATED(`effective ${live.effectiveAt.toISOString()}, after the job at ${f1.firedAt.toISOString()} it read "${f1.statuses[formulary.id] || '?'}"`));
      expect(f1.ok, `Active after the first firing: ${JSON.stringify(f1.statuses)}`).toBe(true);
    });

    await steps.step('Navigate to the Notification Center Management module - the module and the notification feed are shown', async () => {
      await ncDefinitions.open();
      expect(await ncDefinitions.rowIdByName(def.name)).toBe(def.id);
      await expect(notificationBell.bellButton()).toBeVisible();
    });

    await steps.step('Let the daily status update detect the passed expiry - the formulary becomes Expired', async () => {
      const f2 = await fireAndAwait(page, jobClock, 'formulary', [formulary.id], 'expired', expiryAt);
      firedAt = f2.firedAt;
      expect(f2.statuses[formulary.id], `after the firing past the expiry (${expiryAt.toISOString()})`).toBe('expired');
    });

    await steps.step('Check the configured audience\'s feed - a new Expired notification appears with ExpiryDate and TransitionDate', async () => {
      const n = await waitForNotificationAbout(page, def, formularyRef(formulary));
      expect(n, `No "${def.name}" notification about "${formulary.nameEn}" arrived`).not.toBeNull();
      const values = valuesOf(n);
      const record = await readFormulary(page, formulary.id);
      expect(sameDay(values.ExpiryDate, record.expiryDate), `ExpiryDate "${values.ExpiryDate}" vs ${record.expiryDate}`).toBe(true);
      expect(sameDay(values.TransitionDate, firedAt), `TransitionDate "${values.TransitionDate}"`).toBe(true);
      expect((await bellRowFor(notificationBell, def))?.text ?? '').toContain(formulary.nameEn);
    });
  });

  test(`TC-${CASES.expiringSoonAtBoundary.azureId}: should send Expiring Soon for a formulary exactly at the reminder threshold`, async ({ steps, page, jobClock, suiteDefinitions, ncDefinitions, notificationBell }) => {
    let def!: ProbeDefinition;
    let formulary!: ProvisionedFormulary;
    let threshold = 0;
    let n: InboxNotification | null = null;

    await steps.critical('Precondition: an active "Expiring Soon - Formulary" definition and an Active suite formulary expiring exactly the reminder period ahead', async () => {
      threshold = await reminderDays(page);
      def = await statusDefinition(page, suiteDefinitions, 'formulary', 'expiringSoon');
      formulary = await activeFormulary(page, inWindowExpiry(threshold));
      expect(riyadhDayDiff(formulary.expiryDate, new Date()), 'days to the expiry').toBe(threshold);
      expect(await statusOf(page, 'formulary', formulary.id), 'the formulary is Active (approval path)').toBe('active');
    });

    await steps.step('Navigate to the Notification Center Management module - the module and the notification feed are shown', async () => {
      await ncDefinitions.open();
      expect(await ncDefinitions.rowIdByName(def.name)).toBe(def.id);
      await expect(notificationBell.bellButton()).toBeVisible();
    });

    await steps.step('Let the daily reminder process evaluate the formulary at the boundary - it is within the reminder period', async () => {
      const reminder = await awaitReminder(page, jobClock, 'formulary', def, formularyRef(formulary), { extraFirings: REMINDER_FIRINGS });
      n = reminder.notification;
      expect(await statusOf(page, 'formulary', formulary.id), `still Active after the formulary job (${reminder.extraFirings.map((d) => d.toISOString()).join(', ')})`).toBe('active');
      expect(riyadhDayDiff(formulary.expiryDate, new Date()), `days remaining vs reminder before ${threshold}`).toBeLessThanOrEqual(threshold);
    });

    await steps.step('Check the feed - an Expiring Soon notification appears with Entity, DaysRemaining and ExpiryDate', async () => {
      expect(n, `No "${def.name}" notification about "${formulary.nameEn}" (${threshold} days to its expiry ${formulary.expiryDate}) arrived after ${REMINDER_FIRINGS} formulary-job firings`).not.toBeNull();
      const values = valuesOf(n);
      expect(values[entityVariable(def, 'formulary')]).toBe(formulary.nameEn);
      expect(values.DaysRemaining, `DaysRemaining in "${n?.englishMessage}"`).toBe(String(riyadhDayDiff(formulary.expiryDate, new Date())));
      expect(sameDay(values.ExpiryDate, formulary.expiryDate), `ExpiryDate "${values.ExpiryDate}" vs ${formulary.expiryDate}`).toBe(true);
      expect((await bellRowFor(notificationBell, def))?.text ?? '').toContain(formulary.nameEn);
    });
  });

  test(`TC-${CASES.noReminderOutsideWindow.azureId}: should not send Expiring Soon for a formulary one day outside the reminder window`, async ({ steps, page, jobClock, suiteDefinitions, ncDefinitions, notificationBell }) => {
    let def!: ProbeDefinition;
    let outside!: ProvisionedFormulary;
    let control!: ProvisionedFormulary;
    let threshold = 0;
    let outsideDays = 0;

    await steps.critical('Precondition: an active "Expiring Soon - Formulary" definition, a formulary expiring threshold + 1 day ahead and an in-window control', async () => {
      threshold = await reminderDays(page);
      def = await statusDefinition(page, suiteDefinitions, 'formulary', 'expiringSoon');
      outside = await activeFormulary(page, outOfWindowExpiry(threshold + 1));
      outsideDays = riyadhDayDiff(outside.expiryDate, new Date());
      control = await activeFormulary(page, inWindowExpiry(threshold));
      expect(outsideDays, `the outside formulary is one day beyond the window (expiry ${outside.expiryDate})`).toBe(threshold + 1);
    });

    await steps.step('Navigate to the Notification Center Management module - the module and the notification feed are shown', async () => {
      await ncDefinitions.open();
      expect(await ncDefinitions.rowIdByName(def.name)).toBe(def.id);
      await expect(notificationBell.bellButton()).toBeVisible();
    });

    await steps.step('Let the daily reminder process evaluate the formulary one day beyond the reminder period - it is outside the window', async () => {
      const statuses = { outside: await statusOf(page, 'formulary', outside.id), control: await statusOf(page, 'formulary', control.id) };
      expect(statuses, 'both formularies are Active (approval path)').toEqual({ outside: 'active', control: 'active' });
      const reminder = await awaitReminder(page, jobClock, 'formulary', def, formularyRef(control), { extraFirings: REMINDER_FIRINGS });
      blockUnless(steps, reminder.notification !== null, NO_REMINDER_RUN);
    });

    await steps.step('Check the feed - no Expiring Soon notification appears for the formulary outside the window', async () => {
      const about = await notificationsAbout(page, def, formularyRef(outside));
      expect(about.map((x) => x.englishMessage), `Expiring Soon about "${outside.nameEn}"`).toEqual([]);
    });
  });

  test(`TC-${CASES.allApplicableTypes.azureId}: should deliver Inactive, Expired and Expiring Soon formulary notifications with their placeholders and never an Active one`, async ({ steps, page, jobClock, suiteDefinitions, ncDefinitions, notificationBell }) => {
    const kinds: StatusKind[] = ['inactive', 'expired', 'expiringSoon'];
    let defs!: Record<StatusKind, ProbeDefinition>;
    let toDeactivate!: ProvisionedFormulary;
    let expiring!: ProvisionedFormulary;
    let soon!: ProvisionedFormulary;
    const got: Partial<Record<StatusKind, InboxNotification | null>> = {};
    let expiry: FormularyExpiryRun = { activated: false, expired: false, detail: '' };
    // The kinds this run could produce: Expired only when the formulary job made the short-lived formulary Active.
    let observable: StatusKind[] = [];

    await steps.critical('Precondition: Inactive, Expired and Expiring Soon notifications generated for suite formularies (with an active "Active - Formulary" definition throughout)', async () => {
      defs = await statusDefinitions(page, suiteDefinitions, 'formulary', ['active', ...kinds]);
      const threshold = await reminderDays(page);
      toDeactivate = await activeFormulary(page);
      soon = await activeFormulary(page, inWindowExpiry(threshold));
      const expiryAt = inMs(SHORT_EXPIRY_IN_MS);
      const live = await formularyGoingLive(page, expiryAt);
      expiring = live.formulary;
      expiry = await formularyExpiredByJob(page, jobClock, expiring, live.effectiveAt, expiryAt);
      observable = kinds.filter((k) => k !== 'expired' || expiry.activated);
      await deactivateFormulary(page, toDeactivate, DEACTIVATION_DETAILS);
      got.inactive = await waitForNotificationAbout(page, defs.inactive, formularyRef(toDeactivate), 90_000);
      got.expired = await expiredNotification(page, defs.expired, expiring, expiry);
      got.expiringSoon = (await awaitReminder(page, jobClock, 'formulary', defs.expiringSoon, formularyRef(soon), { waitMs: 30_000, extraFirings: REMINDER_FIRINGS })).notification;
      expect(expiry.expired || !expiry.activated, `the Active short-lived formulary should be Expired by the formulary job: ${expiry.detail}`).toBe(true);
    });

    await steps.step('Navigate to the Notification Center Management module - the module and the notification feed are shown', async () => {
      await ncDefinitions.open();
      expect(await ncDefinitions.rowIdByName(defs.inactive.name)).toBe(defs.inactive.id);
      await expect(notificationBell.bellButton()).toBeVisible();
    });

    await steps.step('Open each of the three generated notifications - each one is displayed', async () => {
      expect(observable.filter((k) => !got[k]), 'notification types that never arrived').toEqual([]);
      for (const kind of observable) expect((await bellRowFor(notificationBell, defs[kind]))?.type, `the bell lists the ${kind} notification`).toBe(defs[kind].name);
    });

    await steps.step('Verify each placeholder set against the specification and that no Active notification exists', async () => {
      for (const kind of kinds) expect(specNames(defs[kind], 'formulary'), `the ${kind} placeholders`).toEqual([...SPEC_VARIABLES[kind]].sort());
      for (const kind of observable) {
        const message = got[kind]?.englishMessage ?? '(no notification arrived)';
        expect(hasPlaceholder(message), `${kind}: "${message}" still holds a {{placeholder}}`).toBe(false);
        expect(Object.values(valuesOf(got[kind] ?? null)).filter((v) => v === ''), `${kind}: empty values in "${message}"`).toEqual([]);
      }
      const active = [toDeactivate, expiring, soon].map(formularyRef);
      const seen: string[] = [];
      for (const ref of active) seen.push(...(await notificationsAbout(page, defs.active, ref)).map((x) => x.englishMessage));
      expect(seen, 'Active formulary notifications about the suite formularies').toEqual([]);
      // The Expired notification is part of the case: BLOCKED when it could not be produced (unless a step above failed).
      blockUnless(steps, expiry.activated, FORMULARY_NOT_ACTIVATED(expiry.detail));
    });
  });
});
