import { test, expect } from '../../../fixtures';
import {
  ACTIVATION_ACTION,
  BLOCKED_CASES,
  CASE,
  ENTRY_META,
  ENTRY_TIME,
  EXPIRY_ACTION,
  FIELD_CHANGE_ACTION,
  SYSTEM_ACTOR,
  TRANSITION_VALUE,
  UTC_TOLERANCE_MS,
  VIEWER_TIME_ZONE,
  VIEWER_UTC_OFFSET_MINUTES,
  entryTime,
  isDescending,
} from '../../../data/plans/planAuditTrail.data';

/**
 * User story 14157: View a dedicated audit trail for a plan.
 * The plan-level timeline: its order, what each entry shows, the System actor,
 * UTC timestamps, the empty state, and the lifecycle transitions it records.
 * Twin: tests/network/20-view-network-audit-history.
 *
 * Each case builds its own plan (fixture `planIn`) and opens it by id.
 */
test.describe('US 14157 - Plan audit trail entries', () => {
  test(`TC-${CASE.orderedTrail}: should list the page's audit entries newest first when the Audit History tab is opened`, async ({
    planManagementPage,
    planDetailPage,
    planIn,
    steps,
  }) => {
    test.setTimeout(15 * 60_000);
    const plan = await planIn('Inactive');

    await steps.critical('Navigate to the Plans Management module - the list loads', async () => {
      await planManagementPage.openListFor(plan.payerName);
      expect(await planManagementPage.isListed(plan.name)).toBe(true);
    });

    await steps.critical('Open the plan with recorded audit history - the detail loads', async () => {
      await planDetailPage.open(plan.id);
      expect(await planDetailPage.getName()).toBe(plan.name);
    });

    await steps.critical('Select the Audit History tab - the plan-level audit trail loads', async () => {
      await planDetailPage.audit().open();
      expect((await planDetailPage.audit().readEntries()).length, 'a created, approved and inactivated plan has several entries').toBeGreaterThan(1);
    });

    // Ordered page by page: page 2 may start later than page 1 ends - not a bug (QA lead, 2026-11-01).
    await steps.step('On the page, entries appear with the most recent timestamp first, descending to the oldest', async () => {
      const times = (await planDetailPage.audit().readEntries()).map((entry) => entryTime(entry.when));
      expect(times.filter((time) => Number.isNaN(time)), 'entries without a readable timestamp').toEqual([]);
      expect(isDescending(times), `the timestamps should descend: ${times.map((t) => new Date(t).toISOString()).join(', ')}`).toBe(true);
    });
  });

  test(`TC-${CASE.entryDetail}: should show the action, actor, timestamp and changed fields when a field-change entry is opened`, async ({
    planDetailPage,
    planIn,
    steps,
  }) => {
    test.setTimeout(15 * 60_000);
    const plan = await planIn('Inactive');
    let index = -1;

    await steps.critical('Navigate to the plan - the detail loads', async () => {
      await planDetailPage.open(plan.id);
      expect(await planDetailPage.getName()).toBe(plan.name);
    });

    await steps.critical('Open the plan\'s Audit History tab - the entries load', async () => {
      await planDetailPage.audit().expectEntry(FIELD_CHANGE_ACTION);
    });

    await steps.critical('Locate the entry of a known field change - it is in the list', async () => {
      index = (await planDetailPage.audit().readEntries()).findIndex((entry) => FIELD_CHANGE_ACTION.test(entry.action));
      expect(index, 'an entry recording the field change').toBeGreaterThanOrEqual(0);
    });

    await steps.step('Action, Actor, Timestamp and Changed Fields are all populated and match the change', async () => {
      const tab = planDetailPage.audit();
      const entry = (await tab.readEntries())[index];
      const detail = await tab.openEntry(index);
      await tab.closeEntry();
      expect(detail.action, 'action').toMatch(FIELD_CHANGE_ACTION);
      expect(entry.by, 'actor').not.toBe('');
      expect(entry.when, 'timestamp').toMatch(ENTRY_TIME);
      expect(detail.meta, 'the drawer\'s timestamp and actor').toMatch(ENTRY_META);
      // Rows whose value did not change (e.g. a timestamp) may be listed too - not a bug (QA lead, 2026-11-01).
      expect(detail.changes.length, 'the changed fields').toBeGreaterThan(0);
    });
  });

  test(`TC-${CASE.systemActor}: should label the expiry job's entry with the actor System when a plan was expired automatically`, async ({
    planDetailPage,
    planIn,
    steps,
  }) => {
    test.setTimeout(20 * 60_000);
    const plan = await planIn('Expired');

    await steps.critical('Navigate to the auto-expired plan - the detail loads', async () => {
      await planDetailPage.open(plan.id);
      expect(await planDetailPage.getName()).toBe(plan.name);
    });

    await steps.critical('Open its Audit History tab - the entries load', async () => {
      await planDetailPage.audit().expectEntry(EXPIRY_ACTION);
    });

    await steps.step('The entry generated by the expiry job is in the list', async () => {
      const [newest] = await planDetailPage.audit().readEntries();
      expect(newest.action, 'the newest entry should be the expiry').toMatch(EXPIRY_ACTION);
    });

    await steps.step('Its Actor reads "System", not blank or a user\'s name', async () => {
      const [newest] = await planDetailPage.audit().readEntries();
      expect(newest.by, 'the automated actor').toBe(SYSTEM_ACTOR);
    });
  });

  // A new plan already lists its creation entry, so there is no empty state to show (QA lead, 2026-11-01).
  test(`TC-${CASE.emptyState}: should load the Audit History without an error and list the plan's first entry when a newly created plan is opened`, async ({
    planManagementPage,
    planDetailPage,
    planIn,
    steps,
  }) => {
    const plan = await planIn('Draft');

    await steps.critical('Navigate to the Plans Management module - the list loads', async () => {
      await planManagementPage.openListFor(plan.payerName);
      expect(await planManagementPage.isListed(plan.name)).toBe(true);
    });

    await steps.critical('Open the newly created plan - the detail loads', async () => {
      await planDetailPage.open(plan.id);
      expect(await planDetailPage.getName()).toBe(plan.name);
    });

    await steps.step('Select the Audit History tab - it loads its entries', async () => {
      await planDetailPage.audit().open();
      expect(await planDetailPage.audit().getPanelText(), 'the tab should load').not.toBe('');
    });

    await steps.step('The plan\'s first entry is listed, with no blank area or error', async () => {
      expect((await planDetailPage.audit().readEntries()).length, 'the new plan\'s first entry').toBeGreaterThan(0);
      expect((await planDetailPage.readMessages()).join(' '), 'no error should be shown').not.toMatch(/error|failed|unable/i);
    });
  });

  test(`TC-${CASE.noChangedFields}: should show no invented changed-fields data when an activation entry is opened`, async ({
    planDetailPage,
    planIn,
    steps,
  }) => {
    test.setTimeout(12 * 60_000);
    const plan = await planIn('Active');
    let index = -1;

    await steps.critical('Navigate to the plan - the detail loads', async () => {
      await planDetailPage.open(plan.id);
      expect(await planDetailPage.getName()).toBe(plan.name);
    });

    await steps.critical('Open the plan\'s Audit History tab - the entries load', async () => {
      await planDetailPage.audit().expectEntry(ACTIVATION_ACTION);
    });

    await steps.critical('Locate the activation entry - it is in the list', async () => {
      index = (await planDetailPage.audit().readEntries()).findIndex((entry) => ACTIVATION_ACTION.test(entry.action));
      expect(index, 'the activation entry').toBeGreaterThanOrEqual(0);
    });

    await steps.step('Its Changed Fields are blank or not applicable, with no placeholder data', async () => {
      const tab = planDetailPage.audit();
      const detail = await tab.openEntry(index);
      await tab.closeEntry();
      expect(
        detail.changes.filter((change) => change.field === '' || change.before === change.after),
        'changed-field rows that record no real change',
      ).toEqual([]);
    });
  });

  test(`TC-${CASE.lifecycleTransitions}: should record each lifecycle transition as its own entry in order when a plan went Draft to Active to Expired`, async ({
    planDetailPage,
    planIn,
    steps,
  }) => {
    test.setTimeout(20 * 60_000);
    const plan = await planIn('Expired');

    await steps.critical('Navigate to the expired plan - the detail loads', async () => {
      await planDetailPage.open(plan.id);
      expect(await planDetailPage.getName()).toBe(plan.name);
    });

    await steps.critical('Open its Audit History tab - the entries load', async () => {
      await planDetailPage.audit().expectEntry(EXPIRY_ACTION);
    });

    await steps.step('The Draft-to-Active entry shows its action, actor and timestamp', async () => {
      const tab = planDetailPage.audit();
      const entries = await tab.readEntries();
      const transitions = entries.filter((entry) => ACTIVATION_ACTION.test(entry.action) || EXPIRY_ACTION.test(entry.action));
      expect(transitions.length, 'an activation and an expiry entry').toBeGreaterThanOrEqual(2);
      const activation = transitions[1];
      expect(activation.by, 'actor').not.toBe('');
      expect(activation.when, 'timestamp').toMatch(ENTRY_TIME);
      const detail = await tab.openEntry(entries.indexOf(activation));
      await tab.closeEntry();
      expect(detail.changes.map((change) => change.after).join(' | '), 'the entry should record the move to Active').toMatch(TRANSITION_VALUE.active);
    });

    await steps.step('The Active-to-Expired entry reads Expired, by System, at the job\'s time', async () => {
      const tab = planDetailPage.audit();
      const entries = await tab.readEntries();
      const expiry = entries.find((entry) => EXPIRY_ACTION.test(entry.action));
      expect(expiry, 'the expiry entry').toBeDefined();
      expect(expiry!.by, 'the expiry job\'s actor').toBe(SYSTEM_ACTOR);
      expect(expiry!.when, 'timestamp').toMatch(ENTRY_TIME);
      const detail = await tab.openEntry(entries.indexOf(expiry!));
      await tab.closeEntry();
      expect(detail.changes.map((change) => change.after).join(' | '), 'the entry should record the move to Expired').toMatch(TRANSITION_VALUE.expired);
    });

    await steps.step('The transitions appear in the plan\'s real chronological order', async () => {
      const transitions = (await planDetailPage.audit().readEntries())
        .filter((entry) => ACTIVATION_ACTION.test(entry.action) || EXPIRY_ACTION.test(entry.action));
      const times = transitions.map((entry) => entryTime(entry.when));
      expect(isDescending(times), 'the expiry should be newer than the activation').toBe(true);
    });
  });

  for (const blocked of BLOCKED_CASES) {
    test(`TC-${blocked.azureId}: ${blocked.title}`, async ({ steps }) => {
      steps.blocked(blocked.reason);
    });
  }
});

test.describe('US 14157 - Plan audit trail in UTC', () => {
  test.use({ timezoneId: VIEWER_TIME_ZONE });

  test(`TC-${CASE.utcTimestamps}: should show audit timestamps in UTC when the viewer's time zone is UTC+5`, async ({
    planManagementPage,
    planDetailPage,
    planIn,
    steps,
  }) => {
    const madeFrom = Date.now();
    const plan = await planIn('PendingApproval');
    const madeTo = Date.now();

    await steps.critical('Navigate to the Plans Management module - the list loads', async () => {
      await planManagementPage.openListFor(plan.payerName);
      expect(await planManagementPage.isListed(plan.name)).toBe(true);
    });

    await steps.critical('Set the viewing session to a non-UTC time zone - the browser reports UTC+5', async () => {
      expect(await planDetailPage.getBrowserUtcOffsetMinutes()).toBe(VIEWER_UTC_OFFSET_MINUTES);
    });

    await steps.critical('Open the plan\'s Audit History tab - the entries load', async () => {
      await planDetailPage.open(plan.id);
      await planDetailPage.audit().open();
      expect((await planDetailPage.audit().readEntries()).length, 'a submitted plan has entries').toBeGreaterThan(0);
    });

    await steps.step('Each displayed timestamp is the UTC time it was recorded at, not the local UTC+5 time', async () => {
      const entries = await planDetailPage.audit().readEntries();
      const outside = entries.filter((entry) => {
        const asUtc = entryTime(entry.when, true);
        return !(asUtc >= madeFrom - UTC_TOLERANCE_MS && asUtc <= madeTo + UTC_TOLERANCE_MS);
      });
      expect(
        outside.map((entry) => `${entry.action} at ${entry.when}`),
        `every entry was recorded between ${new Date(madeFrom).toISOString()} and ${new Date(madeTo).toISOString()} UTC`,
      ).toEqual([]);
    });
  });
});
