/**
 * US 15132 "Create a facility" (facility folder 02), 23 cases.
 *
 * How the cases map onto the live drawer (2026-11-04, Facility-Foundation-Notes.md):
 *  - "Create" is the list's Add Facility button; the form is the DRAWER "Add New
 *    Facility" with two steps - 1 Basic Information, 2 Contact & License (the cases'
 *    "tabs"). "Submit" is the drawer's Save; on step 1 the drawer's Next is the submit
 *    (it validates step 1 and sends nothing when it refuses - utils/facility/writerAHelpers
 *    `submitForm`).
 *  - "Complete all other mandatory fields" for a STEP-1 field (17589 / 17590): every
 *    field of both steps is filled, the drawer goes back to step 1 and the one field is
 *    cleared, then Submit. For a missing SELECT (17596 type, 17597 provider type) the
 *    step-2 fields cannot be reached (Next refuses) and a select cannot be cleared, so
 *    only step 1 is filled - noted, not a finding.
 *  - "No record is created" is checked as the dashboard Total unchanged (and, where a
 *    name was entered, no facility of that name).
 *  - Names: every name the suite may save carries the suite prefix (`QA Automation
 *    Facility ...`) and an Arabic name of Arabic letters only (`منشأة <letters>`), so the
 *    cleanup can remove it - "Al Noor Clinic" / "عيادة النور" (17591, 17593) and "Al Amal
 *    Hospital" (17590) become suite names with that label. 17589's Arabic name
 *    "مستشفى الأمل" is typed as given (that save is refused for the blank English name).
 *    17593's "existing facility" is the case's own suite facility (its two names reused).
 *  - Facility Code: generated by the server and shown on the list and the Overview, but
 *    NOT on the form (Add or Edit) - 17592 reopens the facility's (edit) form and looks
 *    for the code there (the finding). 17594 "open a saved facility record" is read as the
 *    record's detail page (Overview) - the full code, not cut off, at most 20 characters
 *    (decision item: the foundation listed 17594 with the form finding; the case's words
 *    "open a saved facility record" fit the detail page).
 *  - 17602 expects the SAME-day expiry to be refused; the screen and server accept it
 *    (the finding). When that save goes through, the earlier-date half reopens Add.
 *  - 17607 / 17608: phone, mobile and coordinates have no validation (screen or server -
 *    the findings). The error slots are read where the drawer's convention puts them
 *    (constants/facility/writerAIds FACILITY_FORM_EXPECTED_ERROR).
 *  - 17610: the "non-Facility Administrator" is the Payer Admin shaped through the
 *    `facilityRole` fixture: the list granted (it lacks GetFacilities), CreateFacility
 *    withheld. "Access the create form directly" is a CreateFacility request as that
 *    account (the form is a drawer, it has no route of its own).
 */

